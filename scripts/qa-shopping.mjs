    await page.getByRole('button', { name: 'Review order', exact: true }).click();
    await page.getByRole('heading', { name: 'Your order, considered.' }).waitFor();
    assert.match(await page.locator('.review-details').textContent(), /Free collection by arrangement/);
    const stored = await page.evaluate(() => localStorage.getItem('herby-health-cart-v1'));
    assert.equal(stored.includes('Ada'), false);
    assert.equal(stored.includes('price'), false);
    await page.getByRole('button', { name: 'Remove Hibiscus from bag' }).click();
    await page.getByRole('heading', { name: 'Your bag is still growing.' }).waitFor();
